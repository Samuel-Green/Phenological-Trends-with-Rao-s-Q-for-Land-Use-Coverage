###############################################################################
# 05.2A_Knepp_NDVI_TWDTW-RaoQ_SG-Filtered.R
# Processes ONE 72-layer tile for TWDTW Rao's Q on the 2019-2024 SG-filtered NDVI stack
###############################################################################

library(terra)
library(rasterdiv)
library(twdtw)

# 1. Grab the tile index passed by the SLURM --array scheduler (1 to 750)
tile_id <- as.numeric(Sys.getenv("SLURM_ARRAY_TASK_ID"))

cat("Starting Knepp SG Filtered NDVI TWDTW tile:", tile_id, "\n")
cat("Start time:", format(Sys.time()), "\n")
flush.console()

# 2. Define directories
base_dir    <- "~/TWDTW_Paper"
tile_dir    <- file.path(base_dir, "Data/Processed Data/Knepp Estate/Knepp_TS_Tiles_NDVI_SG-Filtered")
out_dir     <- file.path(tile_dir, "Rao-utputs")
results_dir <- file.path(base_dir, "Results/Knepp Estate")

dir.create(out_dir, showWarnings = FALSE, recursive = TRUE)

# 3. Construct input and output tile paths matching Step 2 of 05_Analyse_Knepp_Estate_Sentinel_NDVI.R
tile_file <- file.path(
  tile_dir,
  paste0("Knepp_TS_NDVI_SG_Tile-", tile_id, ".tif")
)

# Cleanly exit if this tile index fell inside the empty outer NA corners of the bounding box
if (!file.exists(tile_file)) {
  cat("Tile file missing (Empty Boundary Tile):", tile_file, "- Exiting cleanly.\n")
  quit(save = "no", status = 0)
}

out_file <- file.path(
  out_dir,
  paste0("Knepp_NDVI_TWDTW-RaoQ_SG_Tile-", tile_id, ".tif")
)

# Checkpoint check: skip tiles that have already been computed
if (file.exists(out_file)) {
  cat("Knepp SG NDVI TWDTW Tile", tile_id, "already processed. Skipping.\n")
  flush.console()
  quit(save = "no", status = 0)
}

# 4. Load the optimal TWDTW alpha (stepness) generated by 05.3_Knepp_NDVI_α_Grid-search.R
cat("Loading optimal TWDTW \U03B1 (stepness)...\n")
optimal_alpha_path <- file.path(results_dir, "Knepp_NDVI_Optimal_Alpha.rds")

if (!file.exists(optimal_alpha_path)) {
  stop("Optimal alpha RDS file not found at: ", optimal_alpha_path, 
       "\nEnsure 05.3_Knepp_NDVI_α_Grid-search.R has completed first!")
}

opt_alpha <- readRDS(optimal_alpha_path)
cat("Optimal \U03B1 loaded:", opt_alpha, "\n")

# 5. Load the 72-layer pre-scaled float timeseries tile
cat("Loading tile...\n")
flush.console()

tile_raster <- rast(tile_file)

# 6. Extract the 72-month time vector directly from the raster layer names (e.g., "2019-01_NDVI")
current_names <- names(tile_raster)
dynamic_dates_string <- paste0(sub("_NDVI$", "", current_names), "-15")
dates <- as.Date(dynamic_dates_string, format = "%Y-%m-%d")

# Bulletproof fallback: if GDAL/makeTiles stripped layer names to "lyr.1", reconstruct 2019-2024 dates
if (any(is.na(dates)) || length(dates) != nlyr(tile_raster)) {
  cat("Layer names stripped on disk; reconstructing 2019-2024 monthly calendar...\n")
  dates <- seq(as.Date("2019-01-15"), by = "month", length.out = nlyr(tile_raster))
}

# 7. Run TWDTW Rao's Q across the 72-month trajectory
cat("Running TWDTW Rao's Q...\n")
cat("Rao computation start:", format(Sys.time()), "\n")
flush.console()

res <- paRao(
  x = tile_raster,
  time_vector = dates,
  window = 3,
  alpha = 2,
  na.tolerance = 0,      # Prevents empty background windows from crashing C++ twdtw
  simplify = 2,          # Rounds floats to 2 decimal places
  np = 1,
  progBar = FALSE,       # Prevents SLURM log buffer crashes
  method = "multidimension",
  dist_m = "twdtw",
  midpoint = 2,          # Or 3 if you opt for the 3-month temperate season inflection point
  stepness = opt_alpha,  # Dynamically assigned from your 05.3 Grid Search!
  cycle_length = "year",
  time_scale = "month"
)

cat("Rao computation finished:", format(Sys.time()), "\n")
flush.console()

rao_raster <- res[[1]][[1]]

# Free memory immediately
rm(res, tile_raster)
gc()

# 8. Write output tile to disk
cat("Writing output...\n")
flush.console()

writeRaster(
  rao_raster,
  out_file,
  overwrite = TRUE
)

cat("Knepp SG NDVI TWDTW Tile", tile_id, "completed.\n")
cat("End time:", format(Sys.time()), "\n")
flush.console()